#!/usr/bin/env python3
"""Загружает меши декора (assets/meshes/*.glb, генерирует scripts/gen_meshes.py) в Roblox как
ассеты Model через Open Cloud Assets API (#45).

Формат запроса (create.roblox.com/docs/cloud/guides/usage-assets): POST /assets/v1/assets,
multipart: `request` (JSON: assetType "Model", displayName, description, creationContext.creator)
+ `fileContent` (.glb, Content-Type model/gltf-binary). Ответ — операция, её опрашиваем до done.
Model импортируется как Model с MeshPart внутри — сервер (MeshAssets.server) достаёт MeshPart
через InsertService:LoadAsset и кладёт шаблон в ReplicatedStorage.MeshTemplates.

Уже загруженные (assets/meshes/meshes.json: имя → {id, sha}) пропускаются; изменился файл (sha) —
загружается заново как новый ассет (обновление содержимого Model API принимает только .fbx).
Результат — src/shared/MeshIds.luau ({ имя = assetId }), в лог — MESH_IDS_JSON_BEGIN/END.

Нужно: ROBLOX_API_KEY с Assets API (asset:read + asset:write — те же, что у иконок) и ID владельца
(CREATOR_USER_ID или CREATOR_USERNAME). Ошибки не роняют деплой: без мешей игра строит декор из Part.
"""
import hashlib
import json
import os
import pathlib
import sys
import time
import uuid

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from upload_ui_assets import KEY, creator_id, http  # noqa: E402  (тот же HTTP и владелец)

ROOT = pathlib.Path(__file__).resolve().parent.parent
MESHES = ROOT / "assets" / "meshes"
DB = MESHES / "meshes.json"
OUT = ROOT / "src" / "shared" / "MeshIds.luau"

HELP_403 = (
    "Нет права ключа на загрузку моделей. Владельцу: create.roblox.com → Creator Dashboard → "
    "Open Cloud → API Keys → ключ из секрета ROBLOX_API_KEY → Edit → Access Permissions → "
    "Assets API → Operations: asset:read и asset:write (Model) → Save; IP — 0.0.0.0/0 или IP раннеров. "
    "Ключ не меняется, секрет перекладывать не нужно — следующий деплой загрузит меши сам."
)


def sha(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def upload(path: pathlib.Path, user_id: str):
    boundary = uuid.uuid4().hex
    meta = json.dumps({
        "assetType": "Model",
        "displayName": f"SledMesh_{path.stem}",
        "description": "Sled game decor mesh (generated by scripts/gen_meshes.py)",
        "creationContext": {"creator": {"userId": user_id}},
    })
    body = b"".join([
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n{meta}\r\n".encode(),
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{path.name}\"\r\n"
        f"Content-Type: model/gltf-binary\r\n\r\n".encode(),
        path.read_bytes(),
        f"\r\n--{boundary}--\r\n".encode(),
    ])
    code, resp = http("POST", "https://apis.roblox.com/assets/v1/assets", body,
                      {"x-api-key": KEY, "Content-Type": f"multipart/form-data; boundary={boundary}"})
    if code != 200:
        return None, code, f"HTTP {code}: {resp[:300]}"
    j = json.loads(resp)
    op = j.get("path") or ("operations/" + j["operationId"] if j.get("operationId") else None)
    if not op:
        return None, code, f"нет операции в ответе: {resp[:300]}"
    for _ in range(45):  # модели обрабатываются дольше картинок
        time.sleep(2)
        code, resp = http("GET", f"https://apis.roblox.com/assets/v1/{op}", headers={"x-api-key": KEY})
        if code == 200:
            j = json.loads(resp)
            if j.get("done"):
                if "response" in j:
                    return int(j["response"]["assetId"]), 200, None
                return None, 200, json.dumps(j.get("error") or j)[:300]
    return None, 0, "таймаут операции"


def write_luau(db):
    lines = ["-- Сгенерировано scripts/upload_meshes.py: имя меша → ID ассета Model (Open Cloud, из assets/meshes/*.glb)",
             "return {"]
    for k in sorted(db):
        lines.append(f"\t{k} = {db[k]['id']},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")


def main():
    db = json.loads(DB.read_text()) if DB.exists() else {}
    files = sorted(MESHES.glob("*.glb"))
    todo = [p for p in files if p.stem not in db or db[p.stem].get("sha") != sha(p)]
    if todo and not KEY:
        print("::warning::ROBLOX_API_KEY не задан — меши не загружены (декор остаётся из Part)")
        todo = []
    if todo:
        uid = creator_id()
        print(f"Загружаю {len(todo)} мешей (Model, .glb) от пользователя {uid}")
        for p in todo:
            aid, code, err = upload(p, uid)
            if aid:
                db[p.stem] = {"id": aid, "sha": sha(p)}
                print(f"  {p.stem}: {aid}")
                continue
            print(f"::warning::меш {p.stem}: {err}")
            if code in (401, 403):
                print(f"::warning::{HELP_403}")
                break  # остальные упадут так же
        DB.write_text(json.dumps(db, indent=1, sort_keys=True) + "\n")
    write_luau(db)
    print(f"Мешей с ID: {len(db)} из {len(files)}")
    if KEY and db:
        states = {}
        for name, rec in sorted(db.items()):
            code, body = http("GET", f"https://apis.roblox.com/assets/v1/assets/{rec['id']}?readMask=moderationResult",
                              headers={"x-api-key": KEY})
            st = (json.loads(body).get("moderationResult", {}).get("moderationState", f"HTTP {code}")
                  if code == 200 else f"HTTP {code}: {body[:120]}")
            states.setdefault(st, []).append(name)
        for st, names in states.items():
            print(f"Модерация мешей {st}: {len(names)} — {', '.join(names)}")


if __name__ == "__main__":
    try:
        main()
    except SystemExit as e:
        print(f"::warning::{e}")
        if not OUT.exists():
            write_luau({})
        sys.exit(0)
    except Exception as e:  # деплой не роняем: без мешей игра строит декор из Part
        print(f"::warning::загрузка мешей: {type(e).__name__}: {e}")
        sys.exit(0)
